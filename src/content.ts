// Palettes have identical keys so the renderer can interpolate theme changes.
function theme(
  id: string,
  name: string,
  architecture: string,
  weather: string,
  sky: string,
  horizon: string,
  far: string,
  mid: string,
  near: string,
  detail: string,
  light: string,
  ground: string,
  rail: string,
  floor: string,
) {
  return {
    id,
    name,
    architecture,
    weather,
    palette: { sky, horizon, far, mid, near, detail, light, ground, rail, floor },
  };
}

