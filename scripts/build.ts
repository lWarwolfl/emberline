import { execFileSync } from "node:child_process";
import path from "node:path";
import fs from "node:fs";
import esbuild from "esbuild";
import prettier from "prettier";
const root = path.resolve(__dirname, "..");

async function main() {
  execFileSync(process.execPath, [require.resolve("typescript/bin/tsc")], {
    cwd: root,
    stdio: "inherit",
  });
  execFileSync(
    process.execPath,
    [require.resolve("typescript/bin/tsc"), "-p", "tsconfig.sw.json"],
    { cwd: root, stdio: "inherit" },
  );
  for (const [entry, output] of [
    ["src/main.ts", "dist/game.js"],
    ["src/service-worker.ts", "sw.js"],
  ] as const) {
    const result = await esbuild.build({
      absWorkingDir: root,
      entryPoints: [entry],
      bundle: true,
      format: "iife",
      target: "es2022",
      write: false,
      legalComments: "none",
      banner: { js: "/* Generated by npm run build. Edit TypeScript in src/, then rebuild. */" },
    });
    const options = await prettier.resolveConfig(path.join(root, output));
    const content = await prettier.format(result.outputFiles[0].text, {
      ...options,
      filepath: output,
    });
    fs.mkdirSync(path.dirname(path.join(root, output)), { recursive: true });
    fs.writeFileSync(path.join(root, output), content);
  }
  const bitcoin = await esbuild.build({
    absWorkingDir: root,
    entryPoints: ["server/bitcoin-proof.ts"],
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node20",
    write: false,
    banner: {
      js: "/* Generated by npm run build from server/bitcoin-proof.ts and locked dependencies. */",
    },
  });
  fs.writeFileSync(
    path.join(root, "server/bitcoin-proof.cjs"),
    await prettier.format(bitcoin.outputFiles[0].text, {
      ...(await prettier.resolveConfig(path.join(root, "server/bitcoin-proof.cjs"))),
      filepath: "server/bitcoin-proof.cjs",
    }),
  );
  console.log("Built type-checked browser, service worker and server Bitcoin verifier.");
}
main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
