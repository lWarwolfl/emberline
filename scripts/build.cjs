const { execFileSync } = require("node:child_process");
const path = require("node:path");
const fs = require("node:fs");
const esbuild = require("esbuild");
const prettier = require("prettier");
const root = path.resolve(__dirname, "..");

async function main() {
  fs.rmSync(path.join(root, ".build"), { recursive: true, force: true });
  execFileSync(process.execPath, [require.resolve("typescript/bin/tsc")], {
    cwd: root,
    stdio: "inherit",
  });
  execFileSync(
    process.execPath,
    [require.resolve("typescript/bin/tsc"), "-p", "tsconfig.sw.json"],
    { cwd: root, stdio: "inherit" },
  );
  for (const [entry, output] of [
    ["src/main.ts", "dist/game.js"],
    ["src/service-worker.ts", "sw.js"],
  ]) {
    const result = await esbuild.build({
      absWorkingDir: root,
      entryPoints: [entry],
      bundle: true,
      format: "iife",
      target: "es2022",
      write: false,
      legalComments: "none",
      banner: { js: "/* Generated by npm run build. Edit TypeScript in src/, then rebuild. */" },
    });
    const options = await prettier.resolveConfig(path.join(root, output));
    const content = await prettier.format(result.outputFiles[0].text, {
      ...options,
      filepath: output,
    });
    fs.mkdirSync(path.dirname(path.join(root, output)), { recursive: true });
    fs.writeFileSync(path.join(root, output), content);
  }
  console.log("Built type-checked browser, service worker and Node test modules.");
}
main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
